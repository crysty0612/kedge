"""
Komodo Periphery integration: generates compose manifests for inbound GitOps redeployment webhooks.
"""

from pathlib import Path
from typing import Tuple


class KomodoIntegration:
    @staticmethod
    def generate_manifest(dest_dir: Path, port: int = 8120) -> Tuple[bool, Path]:
        dest_dir.mkdir(parents=True, exist_ok=True)
        compose_path = dest_dir / "compose.yaml"

        content = f"""# Komodo Periphery Inbound GitOps Agent (Generated by Kedge)
services:
  periphery:
    image: ghcr.io/moghtech/komodo-periphery:latest
    container_name: komodo-periphery
    restart: unless-stopped
    volumes:
      - /var/run/docker.sock:/var/run/docker.sock
    environment:
      - PERIPHERY_PORT={port}
    ports:
      - "{port}:{port}"
"""
        compose_path.write_text(content, encoding="utf-8")
        return True, compose_path
